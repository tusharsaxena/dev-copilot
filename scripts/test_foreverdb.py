class CacheTestBase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp)
        env = mock.patch.dict(os.environ, {"XDG_CACHE_HOME": os.path.join(self.tmp, "cache")})
        env.start()
        self.addCleanup(env.stop)
        self.install = write_install(os.path.join(self.tmp, "AddOns", "ForeverDB"))
        # No test may reach the network: these fail loudly unless a test patches them itself.
        self.net = []
        for name in ("_http_get", "_api_tags", "_ls_remote"):
            p = mock.patch.object(F, name, side_effect=self._no_network(name))
            p.start()
            self.addCleanup(p.stop)

    def _no_network(self, name):
        def fail(*a, **k):
            self.net.append(name)
            raise F.FdbError("network disabled in tests (%s)" % name)
        return fail

    def cache(self, *parts):
        return os.path.join(self.tmp, "cache", "ka0s-seeds", "foreverdb", TAG, *parts)

    def sources(self):
        with open(self.cache("SOURCES.json"), encoding="utf-8") as f:
            return json.load(f)

    def db(self):
        with open(self.cache("foreverdb.json"), encoding="utf-8") as f:
            return json.load(f)


class FetchInstallTest(CacheTestBase):
    def fetch(self, install=None):
        return call("fetch", "--tag", TAG, "--date", "2099-01-03", "--from-install", install or self.install)

    def test_writes_json_and_sources_and_prints_the_path(self):
        rc, out, err = self.fetch()
        self.assertEqual(rc, 0, err)
        self.assertEqual(out.strip(), self.cache().rstrip(os.sep))
        self.assertEqual(self.db(), EXPECTED)
        src = self.sources()
        self.assertEqual((src["tag"], src["date"], src["origin"], src["commit"]),
                         (TAG, "2099-01-03", ["install"], None))
        self.assertEqual([f["path"] for f in src["files"]],
                         ["ForeverDB/ForeverDB.toc", "ForeverDB/ForeverDB.lua", "ForeverDB/ForeverDB_2.lua"])
        self.assertEqual(src["files"][1]["sha256"], F.sha256(LUA_1.encode()))
        self.assertEqual(src["install"]["version"], "2099.01.02.7")
        self.assertEqual(src["counts"]["npc"], {"meta": 2, "parsed": 2})
        self.assertEqual(src["counts"]["abord"], {"meta": 5, "parsed": None})
        self.assertEqual(src["meta"], {"build": "2099-01-02", "hash": "00ff00ff00ff00ff"})
        self.assertNotIn("counts", json.dumps(src["files"]))

    def test_commit_is_recorded_when_a_tag_source_answers(self):
        with mock.patch.object(F, "list_tags", return_value=({TAG: SHA}, "api")):
            self.assertEqual(self.fetch()[0], 0)
        self.assertEqual(self.sources()["commit"], SHA)

    def test_version_mismatch_is_refused_and_writes_nothing(self):
        write_install(self.install, toc=TOC.replace("2099.01.02.7", "2099.01.02.6"))
        rc, _, err = self.fetch()
        self.assertEqual(rc, 1)
        self.assertIn("## Version 2099.01.02.6, not 2099.01.02.7: refusing", err)
        self.assertFalse(os.path.exists(self.cache()))

    def test_cache_is_reused_when_hashes_match_even_from_a_crlf_copy(self):
        self.assertEqual(self.fetch()[0], 0)
        before = os.stat(self.cache("foreverdb.json")).st_mtime_ns
        rc, _, err = self.fetch()
        self.assertEqual(rc, 0)
        self.assertIn("cache re-used", err)
        crlf = write_install(os.path.join(self.tmp, "crlf", "ForeverDB"), crlf=True)
        rc, _, err = self.fetch(crlf)
        self.assertEqual(rc, 0)
        self.assertIn("cache re-used", err)
        self.assertEqual(os.stat(self.cache("foreverdb.json")).st_mtime_ns, before)

    def test_changed_install_or_tampered_cache_is_rebuilt(self):
        self.assertEqual(self.fetch()[0], 0)
        with open(self.cache("foreverdb.json"), "w", encoding="utf-8") as f:
            f.write("{}")
        rc, _, err = self.fetch()
        self.assertNotIn("cache re-used", err)
        self.assertEqual(self.db(), EXPECTED)
        write_install(self.install, lua2=LUA_2.replace("An Invented Errand", "A Renamed Errand"))
        rc, _, err = self.fetch()
        self.assertEqual(rc, 0)
        self.assertNotIn("cache re-used", err)
        self.assertEqual(self.db()["quest"]["900201"][0], "A Renamed Errand")

    def test_core_count_mismatch_is_refused(self):
        write_install(self.install, lua1=LUA_1.replace("npc=2", "npc=3"))
        rc, _, err = self.fetch()
        self.assertEqual(rc, 1)
        self.assertIn("npc: meta.counts 3, parsed 2", err)

    def test_files_without_a_meta_table_are_refused(self):
        write_install(self.install, lua1="ForeverDB = {}\n")
        rc, _, err = self.fetch()
        self.assertEqual(rc, 1)
        self.assertIn("no ForeverDB global with a meta table", err)

    def test_a_reshaped_file_is_refused_with_its_line(self):
        write_install(self.install, lua2=LUA_2 + "return ForeverDB\n")
        rc, _, err = self.fetch()
        self.assertEqual(rc, 1)
        self.assertRegex(err, r"ForeverDB_2\.lua:\d+: unsupported statement 'return'")

    def test_bad_tag_or_date_is_refused(self):
        self.assertEqual(call("fetch", "--tag", "../x", "--date", "2099-01-03")[0], 1)
        self.assertEqual(call("fetch", "--tag", TAG, "--date", "3 Jan")[0], 1)
        self.assertEqual(call("fetch", "--tag", TAG)[0], 2)

    def test_get_and_load(self):
        with self.assertRaises(F.FdbError):
            F.load(TAG)
        self.assertEqual(self.fetch()[0], 0)
        self.assertEqual(F.load(TAG), EXPECTED)
        rc, out, _ = call("get", "--tag", TAG, "npc", "900001", "1")
        self.assertEqual(rc, 0)
        self.assertEqual(json.loads(out), {"900001": EXPECTED["npc"]["900001"], "1": None})
        self.assertEqual(call("get", "--tag", TAG, "nosuch")[0], 1)

    def test_never_touched_the_network_unpatched(self):
        self.fetch()
        self.assertEqual(set(self.net) - {"_api_tags", "_ls_remote"}, set())


class FetchGithubTest(CacheTestBase):
    def serve(self, files):
        def get(url, accept=None):
            prefix = "https://raw.githubusercontent.com/foreverfraddons/forever-db/%s/ForeverDB/" % TAG
            self.assertTrue(url.startswith(prefix), url)
            return files[url[len(prefix):]].encode()
        return get

    def fetch(self, files=None, tags=None):
        files = files or {"ForeverDB.toc": TOC, "ForeverDB.lua": LUA_1, "ForeverDB_2.lua": LUA_2}
        with mock.patch.object(F, "_http_get", side_effect=self.serve(files)) as get, \
                mock.patch.object(F, "list_tags", return_value=(tags or {TAG: SHA}, "api")):
            r = call("fetch", "--tag", TAG, "--date", "2099-01-03")
        return r + (get.call_count,)

    def test_downloads_toc_and_listed_files(self):
        rc, out, err, gets = self.fetch()
        self.assertEqual(rc, 0, err)
        self.assertEqual(gets, 3)
        src = self.sources()
        self.assertEqual((src["origin"], src["commit"], len(src["urls"])), (["github"], SHA, 3))
        self.assertTrue(src["urls"][0].endswith("/%s/ForeverDB/ForeverDB.toc" % TAG))
        self.assertEqual(self.db(), EXPECTED)
        rc, _, err, gets = self.fetch()
        self.assertEqual((rc, gets), (0, 0))
        self.assertIn("cache re-used", err)

    def test_unknown_tag_is_refused(self):
        rc, _, err, gets = self.fetch(tags={"v2099.01.01.1": SHA})
        self.assertEqual((rc, gets), (1, 0))
        self.assertIn("does not exist", err)

    def test_version_mismatch_is_refused(self):
        rc, _, err, _ = self.fetch(files={"ForeverDB.toc": TOC.replace("02.7", "02.8")})
        self.assertEqual(rc, 1)
        self.assertIn("refusing", err)

    def test_install_read_is_confirmed_against_the_tag(self):
        self.assertEqual(call("fetch", "--tag", TAG, "--date", "2099-01-03", "--from-install",
                              write_install(self.install, crlf=True))[0], 0)
        rc, _, err, _ = self.fetch()
        self.assertEqual(rc, 0, err)
        src = self.sources()
        self.assertEqual(src["origin"], ["github", "install"])
        self.assertEqual(src["install"]["version"], "2099.01.02.7")

    def test_install_that_is_not_the_tag_is_refused(self):
        write_install(self.install, lua1=LUA_1.replace("Testa Fixture", "Other Fixture"))
        self.assertEqual(call("fetch", "--tag", TAG, "--date", "2099-01-03",
                              "--from-install", self.install)[0], 0)
        rc, _, err, _ = self.fetch()
        self.assertEqual(rc, 1)
        self.assertIn("is not that build", err)

    def test_user_agent(self):
        seen = []

        class Resp(io.BytesIO):
            def __enter__(self):
                return self

            def __exit__(self, *a):
                return False

        def urlopen(req, timeout=None):
            seen.append(req.get_header("User-agent"))
            return Resp(b"ok")
        with mock.patch.object(F, "_http_get", HTTP_GET), mock.patch.object(F.urllib.request, "urlopen", side_effect=urlopen):
            self.assertEqual(F._http_get("https://example.invalid/x"), b"ok")
        self.assertEqual(seen, ["ka0s-seed-check"])


