def lua_value(src):
    """The value of `x = <src>` run through the reader."""
    return F.parse_lua("x = " + src)["x"]


def write_install(root, toc=TOC, lua1=LUA_1, lua2=LUA_2, crlf=False):
    os.makedirs(root, exist_ok=True)
    for name, body in (("ForeverDB.toc", toc), ("ForeverDB.lua", lua1), ("ForeverDB_2.lua", lua2)):
        data = body.replace("\n", "\r\n") if crlf else body
        with open(os.path.join(root, name), "w", encoding="utf-8", newline="") as f:
            f.write(data)
    return root


def call(*argv):
    """(exit code, stdout, stderr) of foreverdb.main in-process."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            rc = F.main(list(argv))
        except SystemExit as e:
            rc = e.code
    return rc, out.getvalue(), err.getvalue()


class ParserTest(unittest.TestCase):
    def test_numbers(self):
        self.assertEqual(lua_value("{1,-15,7.5,-0.25,4e2,0x1F,-0x10,.5}"),
                         [1, -15, 7.5, -0.25, 400.0, 31, -16, 0.5])
        self.assertIsInstance(lua_value("12"), int)

    def test_strings_and_escapes(self):
        self.assertEqual(lua_value(r'"a\"b\\c\nd\065\x42\u{43}"'), 'a"b\\c\ndABC')
        self.assertEqual(lua_value(r"'it\'s'"), "it's")
        self.assertEqual(lua_value('"a\\z   b"'), "ab")
        self.assertEqual(lua_value("[==[raw ]] text]==]"), "raw ]] text")
        self.assertEqual(lua_value("[[\nfirst newline dropped]]"), "first newline dropped")

    def test_bad_escape_and_unfinished_string_name_the_line(self):
        with self.assertRaisesRegex(F.FdbError, r"^<lua>:2: invalid escape"):
            F.parse_lua('a = 1\nx = "bad \\q"')
        with self.assertRaisesRegex(F.FdbError, r"^<lua>:1: unexpected character"):
            F.parse_lua('x = "never closed')

    def test_literals(self):
        self.assertEqual(lua_value("{true,false,nil,1}"), [True, False, None, 1])
        self.assertIsNone(lua_value("nil"))

    def test_positional_nil_and_trailing_nil(self):
        self.assertEqual(lua_value("{100,6,nil,0}"), [100, 6, None, 0])
        self.assertEqual(lua_value("{1,nil}"), [1])

    def test_keyed_tables(self):
        self.assertEqual(lua_value('{name="x",[5]=2,["c1"]={}}'), {"name": "x", 5: 2, "c1": {}})
        self.assertEqual(lua_value("{[1]=0.49,[2]=0.11}"), [0.49, 0.11])
        self.assertEqual(lua_value("{[1]=1,[3]=3}"), {1: 1, 3: 3})
        self.assertEqual(lua_value('{7,8,map=1}'), {1: 7, 2: 8, "map": 1})
        self.assertEqual(lua_value("{}"), {})
        self.assertEqual(lua_value("{1;2,}"), [1, 2])

    def test_comments_and_crlf(self):
        env = F.parse_lua("-- head\r\n--[==[ block\r\n ]==]\r\nx = {1, -- trailing\r\n 2}\r\n")
        self.assertEqual(env["x"], [1, 2])

    def test_or_and_function_blocks(self):
        env = F.parse_lua("A = A or {}\nlocal D = A\nD.t = D.t or {}\n"
                          ";(function() local t = D.t\nt[3]={1}\nt.k=2\nend)()\n"
                          ";(function() local t = D.t\nt[3]={9}\nend)()\n")
        self.assertEqual(env, {"A": {"t": {3: [9], "k": 2}}})
        self.assertNotIn("D", env)  # a local never leaks into the globals

    def test_assigning_nil_removes(self):
        self.assertEqual(F.parse_lua("A = {}\nA[1] = 5\nA[1] = nil")["A"], {})

    def test_unsupported_statement_names_the_line(self):
        for src in ("x = 1\nreturn x", "x = 1\n\nif x then end", "x = f(1)", "x = 1 + 2"):
            with self.assertRaises(F.FdbError) as cm:
                F.parse_lua(src, "ForeverDB_9.lua")
            self.assertRegex(str(cm.exception), r"^ForeverDB_9\.lua:\d+: ")

    def test_fixture_parses_to_expected(self):
        env = F.parse_lua(LUA_1, "ForeverDB.lua")
        F.parse_lua(LUA_2, "ForeverDB_2.lua", env)
        self.assertEqual(json.loads(json.dumps(env["ForeverDB"])), EXPECTED)


