class StatusTest(CacheTestBase):
    TAGS = {"v2099.01.02.9": SHA, "v2099.01.02.10": "f" * 40, "latest": "e" * 40, "v1": "d" * 40}

    def test_newest_from_the_api(self):
        with mock.patch.object(F, "_api_tags", return_value=dict(self.TAGS)):
            rc, out, _ = call("status", "--json")
        self.assertEqual(rc, 0)
        st = json.loads(out)
        self.assertEqual((st["newest"], st["commit"], st["source"], st["cached"]),
                         ("v2099.01.02.10", "f" * 40, "api", False))
        self.assertTrue(st["cachePath"].endswith(os.path.join("foreverdb", "v2099.01.02.10")))

    def test_falls_back_to_ls_remote_and_prefers_the_peeled_commit(self):
        ls = ("%s\trefs/tags/v2099.01.02.9\n%s\trefs/tags/v2099.01.02.9^{}\n%s\trefs/tags/latest\n"
              % ("a" * 40, "b" * 40, "c" * 40))
        done = subprocess.CompletedProcess([], 0, ls, "")
        with mock.patch.object(F, "_ls_remote", LS_REMOTE), \
                mock.patch.object(F.subprocess, "run", return_value=done):
            rc, out, _ = call("status")
        self.assertEqual(rc, 0)
        self.assertIn("newest v2099.01.02.9 %s (from ls-remote)" % ("b" * 40), out)
        self.assertIn("not cached", out)

    def test_no_source_answers(self):
        rc, _, err = call("status")
        self.assertEqual(rc, 1)
        self.assertIn("no tag source answered", err)

    def test_api_pages_are_followed(self):
        page1 = [{"name": "v2099.01.01.%d" % i, "commit": {"sha": SHA}} for i in range(100)]
        page2 = [{"name": "v2099.01.02.1", "commit": {"sha": "9" * 40}}]
        bodies = iter([json.dumps(page1).encode(), json.dumps(page2).encode()])
        urls = []

        def get(url, accept=None):
            urls.append(url)
            return next(bodies)
        with mock.patch.object(F, "_api_tags", API_TAGS), mock.patch.object(F, "_http_get", side_effect=get):
            tags = F._api_tags()
        self.assertEqual(len(tags), 101)
        self.assertTrue(urls[1].endswith("&page=2"))


LS_REMOTE = F._ls_remote
